// DefaultGoMemLimit caps the daemon's Go heap (the daemon must stay tiny so
// it keeps responding under pressure; measured footprint ~5-8 MiB).
const DefaultGoMemLimit = "32MiB"

// ServiceSpec is what the supervision file describes.
type ServiceSpec struct {
	PaceBin    string            // absolute path of the pace binary
	Mode       string            // PACE_MODE for the daemon ("" = leave to config)
	LogDir     string            // daemon stdout/stderr go to LogDir/daemon.log
	GoMemLimit string            // "" = DefaultGoMemLimit
	Env        map[string]string // extra environment (PACE_HOME, PACE_SOCK, PACE_CONFIG)
}

// PassThroughEnv are the location variables copied from the installing
// shell into the service, so the CLI and the daemon agree on paths.
var PassThroughEnv = []string{"PACE_CONFIG", "PACE_HOME", "PACE_SOCK"}

func (s ServiceSpec) env() [][2]string {
	m := map[string]string{"GOMEMLIMIT": s.GoMemLimit}
	if m["GOMEMLIMIT"] == "" {
		m["GOMEMLIMIT"] = DefaultGoMemLimit
	}
	for k, v := range s.Env {
		if v != "" {
			m[k] = v
		}
	}
	if s.Mode != "" {
		m["PACE_MODE"] = s.Mode
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	out := make([][2]string, 0, len(keys))
	for _, k := range keys {
		out = append(out, [2]string{k, m[k]})
	}
	return out
}

// ValidMode reports whether m is a daemon mode accepted by install.
func ValidMode(m string) bool { return m == "observe" || m == "warn-only" || m == "enforce" }

func xmlEsc(s string) string {
	var b bytes.Buffer
	_ = xml.EscapeText(&b, []byte(s))
	return b.String()
}

// LaunchdPlist renders the per-user LaunchAgent (keys in a fixed order).
func LaunchdPlist(s ServiceSpec) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n")
	w("<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n")
	w("<!-- Generated by 'pace install'; remove with 'pace uninstall'. -->\n")
	w("<plist version=\"1.0\">\n<dict>\n")
	w("\t<key>Label</key>\n\t<string>%s</string>\n", Label)
	w("\t<key>ProgramArguments</key>\n\t<array>\n\t\t<string>%s</string>\n\t\t<string>daemon</string>\n\t</array>\n", xmlEsc(s.PaceBin))
	w("\t<key>RunAtLoad</key>\n\t<true/>\n")
	w("\t<key>KeepAlive</key>\n\t<true/>\n")
	w("\t<key>ThrottleInterval</key>\n\t<integer>1</integer>\n")
	w("\t<key>ProcessType</key>\n\t<string>Interactive</string>\n")
	w("\t<key>Nice</key>\n\t<integer>-5</integer>\n")
	w("\t<key>ExitTimeOut</key>\n\t<integer>5</integer>\n")
	log := filepath.Join(s.LogDir, "daemon.log")
	w("\t<key>StandardOutPath</key>\n\t<string>%s</string>\n", xmlEsc(log))
	w("\t<key>StandardErrorPath</key>\n\t<string>%s</string>\n", xmlEsc(log))
	w("\t<key>EnvironmentVariables</key>\n\t<dict>\n")
	for _, kv := range s.env() {
		w("\t\t<key>%s</key>\n\t\t<string>%s</string>\n", xmlEsc(kv[0]), xmlEsc(kv[1]))
	}
	w("\t</dict>\n")
	w("</dict>\n</plist>\n")
	return b.String()
}

// sdQuote quotes one word for a systemd unit file: specifiers (%) and
// variable references ($) are escaped, and the word is double-quoted when it
// contains spaces, quotes or backslashes.
func sdQuote(s string) string {
	s = strings.ReplaceAll(s, "%", "%%")
	s = strings.ReplaceAll(s, "$", "$$")
	if s != "" && !strings.ContainsAny(s, " \t\"'\\;") {
		return s
	}
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`
}

// SystemdUnit renders the systemd --user unit.
func SystemdUnit(s ServiceSpec) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	log := filepath.Join(s.LogDir, "daemon.log")
	w("# Generated by 'pace install'; remove with 'pace uninstall'.\n")
	w("[Unit]\n")
	w("Description=pace resource governor\n")
	// Never stop restarting: time without the daemon is a fault.
	w("StartLimitIntervalSec=0\n")
	w("\n[Service]\n")
	w("Type=simple\n")
	w("ExecStart=%s daemon\n", sdQuote(s.PaceBin))
	w("Restart=always\n")
	w("RestartSec=1\n")
	w("TimeoutStopSec=5\n")
	for _, kv := range s.env() {
		w("Environment=%s\n", sdQuote(kv[0]+"="+kv[1]))
	}
	w("StandardOutput=append:%s\n", strings.ReplaceAll(log, "%", "%%"))
	w("StandardError=append:%s\n", strings.ReplaceAll(log, "%", "%%"))
	w("Delegate=yes\n")
	w("\n[Install]\n")
	w("WantedBy=default.target\n")
	return b.String()
}

// PlistPath is ~/Library/LaunchAgents/com.pace.daemon.plist.
func PlistPath(home string) string { return plistPathFor(home, Label) }

func plistPathFor(home, label string) string {
	return filepath.Join(home, "Library", "LaunchAgents", label+".plist")
}

// UnitPath is $XDG_CONFIG_HOME/systemd/user/pace.service (default ~/.config).
func UnitPath(home string, env Env) string { return unitPathFor(home, env, UnitName) }

func unitPathFor(home string, env Env, unit string) string {
	base := env.get("XDG_CONFIG_HOME")
	if base == "" {
		base = filepath.Join(home, ".config")
	}
	return filepath.Join(base, "systemd", "user", unit)
}

// Runner runs an external command and returns its combined output. Tests
// inject a fake; production uses ExecRunner. launchctl and systemctl are
// only ever reached through a Runner.
type Runner interface {
	Run(name string, args ...string) ([]byte, error)
}

// ExecRunner runs commands for real with a timeout.
type ExecRunner struct{ Timeout time.Duration }

// Run implements Runner.
func (r ExecRunner) Run(name string, args ...string) ([]byte, error) {
	to := r.Timeout
	if to <= 0 {
		to = 15 * time.Second
	}
	ctx, cancel := context.WithTimeout(context.Background(), to)
	defer cancel()
	return exec.CommandContext(ctx, name, args...).CombinedOutput()
}

// Installer installs and removes the supervised daemon.
type Installer struct {
	GOOS   string // "darwin" | "linux"
	UID    int
	Home   string
	Env    Env
	Runner Runner
	Out    io.Writer
	DryRun bool
	// Sleep is used between polls (nil = time.Sleep).
	Sleep func(time.Duration)
	// Health, if set, is polled after install to confirm the daemon answers.
	Health func() error
	// HealthWait bounds the post-install health poll (0 = 3s).
	HealthWait time.Duration
}

func (i *Installer) out() io.Writer {
	if i.Out == nil {
		return io.Discard
	}
	return i.Out
}

func (i *Installer) sleep(d time.Duration) {
	if i.Sleep != nil {
		i.Sleep(d)
		return
	}
	time.Sleep(d)
}

// run executes a mutating command (printed, skipped on dry run).
func (i *Installer) run(name string, args ...string) ([]byte, error) {
	line := name + " " + strings.Join(quoteAll(args), " ")
	if i.DryRun {
		fmt.Fprintf(i.out(), "would run: %s\n", line)
		return nil, nil
	}
	fmt.Fprintf(i.out(), "run: %s\n", line)
	out, err := i.Runner.Run(name, args...)
	if err != nil {
		return out, fmt.Errorf("%s: %w: %s", line, err, strings.TrimSpace(string(out)))
	}
	return out, nil
}

// query executes a read-only command (also on dry run, never printed).
func (i *Installer) query(name string, args ...string) ([]byte, error) {
	return i.Runner.Run(name, args...)
}

func quoteAll(args []string) []string {
	out := make([]string, len(args))
	for k, a := range args {
		out[k] = ShellQuote(a)
	}
	return out
}

func (i *Installer) target() string { return "gui/" + strconv.Itoa(i.UID) }

func (i *Installer) service() string { return i.serviceFor(Label) }

func (i *Installer) serviceFor(label string) string { return i.target() + "/" + label }

// ServiceState is what Status reports.
type ServiceState struct {
	Manager   string `json:"manager"` // launchd | systemd
	File      string `json:"file"`
	Installed bool   `json:"installed"` // the plist/unit file exists
	Loaded    bool   `json:"loaded"`    // known to the service manager
	Running   bool   `json:"running"`
	PID       int    `json:"pid,omitempty"`
	Detail    string `json:"detail,omitempty"`
}

// Status inspects the service (read-only).
func (i *Installer) Status() (ServiceState, error) {
	switch i.GOOS {
	case "darwin":
		st := ServiceState{Manager: "launchd", File: PlistPath(i.Home)}
		st.Installed = fileExists(st.File)
		out, err := i.query("launchctl", "print", i.service())
		if err != nil {
			return st, nil
		}
		st.Loaded = true
		st.Running, st.PID, st.Detail = parseLaunchctlPrint(string(out))
		return st, nil
	case "linux":
		st := ServiceState{Manager: "systemd", File: UnitPath(i.Home, i.Env)}
		st.Installed = fileExists(st.File)
		out, err := i.query("systemctl", "--user", "show", UnitName, "-p", "LoadState", "-p", "ActiveState", "-p", "MainPID")
		if err != nil {
			return st, fmt.Errorf("systemctl --user show: %w", err)
		}
		props := parseProps(string(out))
		st.Loaded = props["LoadState"] == "loaded"
		st.Running = props["ActiveState"] == "active"
		st.PID, _ = strconv.Atoi(props["MainPID"])
		st.Detail = "ActiveState=" + props["ActiveState"]
		return st, nil
	}
	return ServiceState{}, fmt.Errorf("install: unsupported OS %q", i.GOOS)
}

// parseLaunchctlPrint extracts the top-level state and pid from
// `launchctl print gui/<uid>/<label>` output.
func parseLaunchctlPrint(s string) (running bool, pid int, state string) {
	for _, line := range strings.Split(s, "\n") {
		// top-level keys are indented by exactly one tab
		if !strings.HasPrefix(line, "\t") || strings.HasPrefix(line, "\t\t") {
			continue
		}
		k, v, ok := strings.Cut(strings.TrimSpace(line), " = ")
		if !ok {
			continue
		}
		switch k {
		case "state":
			if state == "" {
				state = v
			}
		case "pid":
			if pid == 0 {
				pid, _ = strconv.Atoi(v)
			}
		}
	}
	return state == "running", pid, state
}

func parseProps(s string) map[string]string {
	m := map[string]string{}
	for _, line := range strings.Split(s, "\n") {
		if k, v, ok := strings.Cut(strings.TrimSpace(line), "="); ok {
			m[k] = v
		}
	}
	return m
}

func fileExists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}

// Install writes the service file and (re)starts the daemon under the
// service manager. It is idempotent: an unchanged service is restarted in
// place (upgrade), a changed one is reloaded.
func (i *Installer) Install(s ServiceSpec) error {
	if !filepath.IsAbs(s.PaceBin) {
		return fmt.Errorf("install: pace binary path %q is not absolute", s.PaceBin)
	}
	if s.Mode != "" && !ValidMode(s.Mode) {
		return fmt.Errorf("install: invalid mode %q (want observe|warn-only|enforce)", s.Mode)
	}
	if s.LogDir == "" {
		s.LogDir = DefaultLogDir(i.Env, i.GOOS)
	}
	switch i.GOOS {
	case "darwin":
		return i.installLaunchd(s)
	case "linux":
		return i.installSystemd(s)
	}
	return fmt.Errorf("install: unsupported OS %q", i.GOOS)
}

func (i *Installer) writeFile(path, content string, mode os.FileMode) error {
	if i.DryRun {
		fmt.Fprintf(i.out(), "would write %s:\n%s", path, content)
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := writeFileAtomic(path, []byte(content), mode); err != nil {
		return err
	}
	fmt.Fprintf(i.out(), "wrote %s\n", path)
	return nil
}

func (i *Installer) mkdir(dir string) error {
	if i.DryRun {
		fmt.Fprintf(i.out(), "would create directory %s\n", dir)
		return nil
	}
	return os.MkdirAll(dir, 0o755)
}

func (i *Installer) launchdLoaded() bool { return i.launchdLoadedAs(Label) }

func (i *Installer) launchdLoadedAs(label string) bool {
	_, err := i.query("launchctl", "print", i.serviceFor(label))
	return err == nil
}

func (i *Installer) installLaunchd(s ServiceSpec) error {
	path := PlistPath(i.Home)
	content := LaunchdPlist(s)
	old, _ := os.ReadFile(path)
	loaded := i.launchdLoaded()
	if err := i.mkdir(s.LogDir); err != nil {
		return err
	}
	if loaded && string(old) == content {
		// Same service definition: restart it so a new binary takes over.
		if _, err := i.run("launchctl", "kickstart", "-k", i.service()); err != nil {
			return err
		}
		return i.waitHealthy()
	}
	if loaded {
		if _, err := i.run("launchctl", "bootout", i.service()); err != nil {
			return err
		}
		if !i.DryRun && !i.waitUnloaded(5*time.Second) {
			return fmt.Errorf("install: %s still loaded 5s after bootout", Label)
		}
	}
	if err := i.writeFile(path, content, 0o644); err != nil {
		return err
	}
	if _, err := i.run("launchctl", "bootstrap", i.target(), path); err != nil {
		// A just-booted-out service can take a moment to disappear.
		if i.DryRun {
			return err
		}
		i.sleep(time.Second)
		if _, err2 := i.run("launchctl", "bootstrap", i.target(), path); err2 != nil {
			return err2
		}
	}
	return i.waitHealthy()
}

func (i *Installer) waitUnloaded(max time.Duration) bool {
	const step = 100 * time.Millisecond
	for waited := time.Duration(0); waited <= max; waited += step {
		if !i.launchdLoaded() {
			return true
		}
		i.sleep(step)
	}
	return false
}

func (i *Installer) waitHealthy() error {
	if i.DryRun || i.Health == nil {
		return nil
	}
	max := i.HealthWait
	if max <= 0 {
		max = 3 * time.Second
	}
	const step = 100 * time.Millisecond
	var err error
	for waited := time.Duration(0); waited <= max; waited += step {
		if err = i.Health(); err == nil {
			fmt.Fprintln(i.out(), "daemon is answering")
			return nil
		}
		i.sleep(step)
	}
	return fmt.Errorf("install: service started but the daemon did not answer within %v: %w (see the daemon log)", max, err)
}

func (i *Installer) installSystemd(s ServiceSpec) error {
	path := UnitPath(i.Home, i.Env)
	content := SystemdUnit(s)
	if err := i.mkdir(s.LogDir); err != nil {
		return err
	}
	_, activeErr := i.query("systemctl", "--user", "is-active", "--quiet", UnitName)
	wasActive := activeErr == nil
	if err := i.writeFile(path, content, 0o644); err != nil {
		return err
	}
	if _, err := i.run("systemctl", "--user", "daemon-reload"); err != nil {
		return err
	}
	if _, err := i.run("systemctl", "--user", "enable", "--now", UnitName); err != nil {
		return err
	}
	if wasActive {
		if _, err := i.run("systemctl", "--user", "restart", UnitName); err != nil {
			return err
		}
	}
	return i.waitHealthy()
}

// Uninstall stops the daemon and removes the service file. Logs, state and
// config are kept.
func (i *Installer) Uninstall() error { return i.uninstall(Label, UnitName) }

// UninstallLegacy stops and removes the service gov (pace's old name)
// installed: launchd label com.gov.daemon or systemd unit gov.service.
func (i *Installer) UninstallLegacy() error { return i.uninstall(LegacyLabel, LegacyUnitName) }

func (i *Installer) uninstall(label, unit string) error {
	switch i.GOOS {
	case "darwin":
		path := plistPathFor(i.Home, label)
		loaded := i.launchdLoadedAs(label)
		if !loaded && !fileExists(path) {
			fmt.Fprintln(i.out(), "not installed")
			return nil
		}
		if loaded {
			if _, err := i.run("launchctl", "bootout", i.serviceFor(label)); err != nil {
				return err
			}
		}
		return i.remove(path)
	case "linux":
		path := unitPathFor(i.Home, i.Env, unit)
		if !fileExists(path) {
			fmt.Fprintln(i.out(), "not installed")
			return nil
		}
		// disable may fail if the unit was never enabled; keep going.
		if _, err := i.run("systemctl", "--user", "disable", "--now", unit); err != nil {
			fmt.Fprintf(i.out(), "warning: %v\n", err)
		}
		if err := i.remove(path); err != nil {
			return err
		}
		_, err := i.run("systemctl", "--user", "daemon-reload")
		return err
	}
	return fmt.Errorf("uninstall: unsupported OS %q", i.GOOS)
}

func (i *Installer) remove(path string) error {
	if i.DryRun {
		fmt.Fprintf(i.out(), "would remove %s\n", path)
		return nil
	}
	if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	fmt.Fprintf(i.out(), "removed %s\n", path)
	return nil
}

// CheckBinaryPath rejects pace binaries that will not survive (go run's
// build cache) and returns warnings for suspicious locations.
func CheckBinaryPath(p string) (warnings []string, err error) {
	if !filepath.IsAbs(p) {
		return nil, fmt.Errorf("pace binary path %q is not absolute", p)
	}
	if strings.Contains(p, "/go-build") {
		return nil, fmt.Errorf("pace binary %s is a 'go run' temporary; build it first (go build -o ~/bin/pace ./cmd/pace)", p)
	}
	for _, tmp := range []string{"/tmp/", "/private/tmp/", "/private/var/folders/", "/var/folders/"} {
		if strings.HasPrefix(p, tmp) {
			warnings = append(warnings, fmt.Sprintf("pace binary %s is in a temporary directory; the service breaks if it is cleaned", p))
		}
	}
	return warnings, nil
}

// ShimMarker is on the second line of every generated shim. Only files that
// carry it are ever overwritten, removed, or skipped during PATH lookup.
const ShimMarker = "# pace-shim v1"

// ShellQuote quotes s for POSIX sh using single quotes.
func ShellQuote(s string) string {
	if s != "" && strings.IndexFunc(s, func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("-_./+:@%=,", r))
	}) < 0 {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// ValidToolName reports whether name can be a shim file name.
func ValidToolName(name string) bool {
	if name == "" || name == "." || name == ".." || len(name) > 64 {
		return false
	}
	for _, r := range name {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '.' || r == '_' || r == '-' || r == '+') {
			return false
		}
	}
	return true
}

// ShimScript returns the sh script for tool name. It execs
// `<paceBin> shim-exec <name> "$@"`. If paceBin has gone missing it still runs
// the real tool (with shimDir removed from PATH) after one DEGRADED line, so
// a broken install never breaks the user's tools.
func ShimScript(paceBin, name, shimDir string) string {
	q := ShellQuote(name)
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString(ShimMarker + ": routes heavy '" + name + "' commands through 'pace run'.\n")
	b.WriteString("# Generated by 'pace shims install'; remove with 'pace shims uninstall'.\n")
	b.WriteString("g=" + ShellQuote(paceBin) + "\n")
	b.WriteString("if [ -x \"$g\" ]; then exec \"$g\" shim-exec " + q + " \"$@\"; fi\n")
	b.WriteString("# pace is missing: run the real tool with this directory removed from PATH.\n")
	b.WriteString("d=" + ShellQuote(shimDir) + "\n")
	// Loop guard: if this fallback already ran for this tool in this exec
	// chain (the PATH entry naming this directory was spelled differently,
	// or another shim directory is also stale), the real tool is not on PATH.
	b.WriteString("case \":${PACE_SHIM_FALLBACK:-}:\" in *:" + q + ":*)\n")
	b.WriteString("\techo \"pace: DEGRADED reason=pace_missing msg=\\\"" + name + ": real tool not found outside pace shim directories\\\"\" >&2; exit 127 ;;\nesac\n")
	b.WriteString("PACE_SHIM_FALLBACK=${PACE_SHIM_FALLBACK:+$PACE_SHIM_FALLBACK:}" + q + "; export PACE_SHIM_FALLBACK\n")
	b.WriteString("echo \"pace: DEGRADED reason=pace_missing msg=\\\"shim cannot run $g; running " + name + " unguarded\\\"\" >&2\n")
	// Drop every PATH entry that is this directory, however it is spelled
	// (a//b, a/./b, a symlink): compare physical paths too.
	b.WriteString("dp=$(cd \"$d\" 2>/dev/null && pwd -P)\n")
	b.WriteString("p=; set -f; IFS=:\n")
	b.WriteString("for e in $PATH; do\n")
	b.WriteString("\t[ \"$e\" = \"$d\" ] || [ \"$e\" = \"$d/\" ] && continue\n")
	b.WriteString("\tcase $e in /*) [ -n \"$dp\" ] && [ \"$(cd \"$e\" 2>/dev/null && pwd -P)\" = \"$dp\" ] && continue ;; esac\n")
	b.WriteString("\tp=\"${p:+$p:}$e\"\n")
	b.WriteString("done\n")
	b.WriteString("unset IFS; set +f\n")
	b.WriteString("PATH=$p; export PATH\n")
	b.WriteString("exec " + q + " \"$@\"\n")
	return b.String()
}

// IsShim reports whether path is a pace-generated shim (reads ≤ 256 bytes).
func IsShim(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	buf := make([]byte, 256)
	n, _ := io.ReadFull(f, buf)
	return bytes.Contains(buf[:n], []byte(ShimMarker))
}

// ShimOptions configure InstallShims.
type ShimOptions struct {
	Dir     string   // shim directory
	PaceBin string   // absolute path of the pace binary
	Tools   []string // tool names; empty = HeavyTools()
	DryRun  bool
	Out     io.Writer // progress lines; nil = discard
}

// InstallShims writes one shim per tool into o.Dir (created 0755). Existing
// pace shims are replaced; any other file with a tool's name is left alone
// and reported as an error. Returns the shim paths written (or that would be
// written on a dry run).
func InstallShims(o ShimOptions) ([]string, error) {
	out := o.Out
	if out == nil {
		out = io.Discard
	}
	if o.Dir == "" {
		return nil, errors.New("shims: no directory")
	}
	if !filepath.IsAbs(o.PaceBin) {
		return nil, fmt.Errorf("shims: pace binary path %q is not absolute", o.PaceBin)
	}
	dir := filepath.Clean(o.Dir)
	tools := o.Tools
	if len(tools) == 0 {
		tools = HeavyTools()
	}
	tools = dedupSorted(tools)
	for _, t := range tools {
		if !ValidToolName(t) {
			return nil, fmt.Errorf("shims: invalid tool name %q", t)
		}
		if t == "pace" {
			return nil, errors.New("shims: refusing to shim pace itself")
		}
	}
	if o.DryRun {
		fmt.Fprintf(out, "would create directory %s\n", dir)
	} else if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("shims: %w", err)
	}
	var written []string
	var errs []error
	for _, t := range tools {
		p := filepath.Join(dir, t)
		if fi, err := os.Lstat(p); err == nil {
			if !fi.Mode().IsRegular() || !IsShim(p) {
				errs = append(errs, fmt.Errorf("shims: %s exists and is not a pace shim; left alone", p))
				continue
			}
		}
		content := ShimScript(o.PaceBin, t, dir)
		if o.DryRun {
			fmt.Fprintf(out, "would write %s\n", p)
			written = append(written, p)
			continue
		}
		if err := writeFileAtomic(p, []byte(content), 0o755); err != nil {
			errs = append(errs, fmt.Errorf("shims: %w", err))
			continue
		}
		fmt.Fprintf(out, "wrote %s\n", p)
		written = append(written, p)
	}
	return written, errors.Join(errs...)
}

// UninstallShims removes every pace shim in dir (files without the marker are
// kept) and the directory itself if it ends up empty.
func UninstallShims(dir string, dryRun bool, out io.Writer) ([]string, error) {
	if out == nil {
		out = io.Discard
	}
	ents, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("shims: %w", err)
	}
	var removed []string
	var errs []error
	kept := 0
	for _, e := range ents {
		p := filepath.Join(dir, e.Name())
		if !e.Type().IsRegular() || !IsShim(p) {
			kept++
			continue
		}
		if dryRun {
			fmt.Fprintf(out, "would remove %s\n", p)
			removed = append(removed, p)
			continue
		}
		if err := os.Remove(p); err != nil {
			errs = append(errs, err)
			kept++
			continue
		}
		fmt.Fprintf(out, "removed %s\n", p)
		removed = append(removed, p)
	}
	if kept == 0 {
		if dryRun {
			fmt.Fprintf(out, "would remove directory %s\n", dir)
		} else if err := os.Remove(dir); err == nil {
			fmt.Fprintf(out, "removed directory %s\n", dir)
		}
	}
	return removed, errors.Join(errs...)
}

// ShimInfo describes one installed shim.
type ShimInfo struct {
	Name string `json:"name"`
	Path string `json:"path"`
	Real string `json:"real,omitempty"` // the binary the shim resolves to ("" = not found)
}

// ListShims returns the pace shims in dir, sorted by name, with the real
// binary each resolves to under pathEnv.
func ListShims(dir, pathEnv string) ([]ShimInfo, error) {
	ents, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var out []ShimInfo
	for _, e := range ents {
		p := filepath.Join(dir, e.Name())
		if !e.Type().IsRegular() || !IsShim(p) {
			continue
		}
		real, _ := LookPathExcluding(e.Name(), pathEnv, []string{dir}, "")
		out = append(out, ShimInfo{Name: e.Name(), Path: p, Real: real})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

// ErrNotFound is returned by LookPathExcluding when no candidate exists.
var ErrNotFound = errors.New("executable not found in PATH")

// LookPathExcluding finds name in pathEnv like exec.LookPath, skipping the
// excluded directories (compared after Clean and symlink resolution), any
// file that is a pace shim, and the file self (the pace binary; "" = none).
// Relative PATH entries (including empty ones, meaning ".") are skipped:
// a shim must never resolve to something in the current directory.
func LookPathExcluding(name, pathEnv string, exclude []string, self string) (string, error) {
	if strings.ContainsRune(name, '/') || name == "" {
		return "", fmt.Errorf("%q: %w", name, ErrNotFound)
	}
	ex := make([]string, 0, 2*len(exclude))
	for _, d := range exclude {
		if d == "" {
			continue
		}
		ex = append(ex, filepath.Clean(d))
		if r, err := filepath.EvalSymlinks(d); err == nil {
			ex = append(ex, filepath.Clean(r))
		}
	}
	var selfFI os.FileInfo
	if self != "" {
		selfFI, _ = os.Stat(self)
	}
	for _, dir := range filepath.SplitList(pathEnv) {
		if dir == "" || !filepath.IsAbs(dir) {
			continue
		}
		cd := filepath.Clean(dir)
		if containsPath(ex, cd) {
			continue
		}
		if r, err := filepath.EvalSymlinks(cd); err == nil && containsPath(ex, filepath.Clean(r)) {
			continue
		}
		p := filepath.Join(cd, name)
		fi, err := os.Stat(p)
		if err != nil || fi.IsDir() || fi.Mode()&0o111 == 0 {
			continue
		}
		if selfFI != nil && os.SameFile(fi, selfFI) {
			continue
		}
		if fi.Size() < 4096 && IsShim(p) {
			continue
		}
		return p, nil
	}
	return "", fmt.Errorf("%q: %w", name, ErrNotFound)
}

func containsPath(list []string, p string) bool {
	for _, x := range list {
		if x == p {
			return true
		}
	}
	return false
}

// PathIndex returns the index of dir in pathEnv (after Clean), or -1.
func PathIndex(pathEnv, dir string) int {
	d := filepath.Clean(dir)
	for i, e := range filepath.SplitList(pathEnv) {
		if e != "" && filepath.Clean(e) == d {
			return i
		}
	}
	return -1
}

func dedupSorted(in []string) []string {
	m := map[string]bool{}
	var out []string
	for _, s := range in {
		s = strings.TrimSpace(s)
		if s == "" || m[s] {
			continue
		}
		m[s] = true
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}

// writeFileAtomic writes data to a temp file in the same directory and
// renames it over path.
func writeFileAtomic(path string, data []byte, mode os.FileMode) error {
	dir := filepath.Dir(path)
	f, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp*")
	if err != nil {
		return err
	}
	tmp := f.Name()
	ok := false
	defer func() {
		if !ok {
			os.Remove(tmp)
		}
	}()
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err := f.Chmod(mode); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		return err
	}
	ok = true
	return nil
}

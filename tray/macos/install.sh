#!/bin/sh
# Installs PaceBar.app (the pace menu bar icon) for the current user:
# copies it to ~/Applications and starts it at login with a LaunchAgent
# (com.pace.bar). It restarts after a crash, not after Quit.
#   install.sh [path/to/PaceBar.app]   install or upgrade (default: dist/PaceBar.app)
#   install.sh --uninstall            stop it and remove the app and the agent
set -eu
here=$(cd "$(dirname "$0")" && pwd)
label=com.pace.bar
plist=$HOME/Library/LaunchAgents/$label.plist
dest=$HOME/Applications/PaceBar.app
uid=$(id -u)

# Before the rename this app was GovBar (agent com.gov.bar): remove it.
if [ -e "$HOME/Library/LaunchAgents/com.gov.bar.plist" ] || [ -e "$HOME/Applications/GovBar.app" ]; then
	launchctl bootout "gui/$uid/com.gov.bar" 2>/dev/null || true
	rm -f "$HOME/Library/LaunchAgents/com.gov.bar.plist"
	rm -rf "$HOME/Applications/GovBar.app"
	echo "removed the old GovBar"
fi

if [ "${1:-}" = "--uninstall" ]; then
	launchctl bootout "gui/$uid/$label" 2>/dev/null || true
	rm -f "$plist"
	rm -rf "$dest"
	echo "PaceBar removed"
	exit 0
fi

src=${1:-$here/../../dist/PaceBar.app}
[ -x "$src/Contents/MacOS/PaceBar" ] || { echo "no PaceBar.app at $src (run tray/macos/build.sh first)" >&2; exit 1; }

pace=${PACE_BIN:-}
if [ -z "$pace" ]; then
	for g in "$HOME/.local/bin/pace" "$HOME/bin/pace" "$HOME/go/bin/pace" /opt/homebrew/bin/pace /usr/local/bin/pace; do
		[ -x "$g" ] && { pace=$g; break; }
	done
fi
[ -n "$pace" ] || { echo "pace not found; set PACE_BIN=/path/to/pace" >&2; exit 1; }

launchctl bootout "gui/$uid/$label" 2>/dev/null || true
mkdir -p "$HOME/Applications" "$HOME/Library/LaunchAgents"
tmp=$dest.new.$$
rm -rf "$tmp"
cp -R "$src" "$tmp"
rm -rf "$dest"
mv "$tmp" "$dest"

cat >"$plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by tray/macos/install.sh; remove with install.sh --uninstall. -->
<plist version="1.0">
<dict>
	<key>Label</key><string>$label</string>
	<key>ProgramArguments</key>
	<array><string>$dest/Contents/MacOS/PaceBar</string></array>
	<key>EnvironmentVariables</key>
	<dict><key>PACE_BIN</key><string>$pace</string></dict>
	<key>RunAtLoad</key><true/>
	<key>KeepAlive</key>
	<dict><key>SuccessfulExit</key><false/></dict>
	<key>LimitLoadToSessionType</key><string>Aqua</string>
	<key>ProcessType</key><string>Interactive</string>
</dict>
</plist>
EOF
launchctl bootstrap "gui/$uid" "$plist"
echo "PaceBar installed: $dest (pace: $pace); it starts at login"
